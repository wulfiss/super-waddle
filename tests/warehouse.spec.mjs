import {openFromBakeryHome} from './helpers/sidebar.mjs';
import {test,expect} from '@playwright/test';
test('warehouse sees categorized products and account names, persists registration and downloads Excel',async({page})=>{
 await page.goto('/');
 await openFromBakeryHome(page,'Nuevo pedido');await page.getByRole('button',{name:'Pan de campo unidades'}).click();await page.getByLabel('Cantidad de Pan de campo',{exact:true}).fill('1');
 await page.getByRole('button',{name:'Agregar al pedido',exact:true}).click();
 await page.getByRole('button',{name:'Insumos',exact:true}).click();
 await page.getByRole('button',{name:'Manga descartable unidades'}).click();
 await page.getByLabel('Cantidad de Manga descartable',{exact:true}).fill('2');
 await page.getByRole('button',{name:'Agregar al pedido',exact:true}).click();
 await page.getByRole('button',{name:/^Revisar pedido/}).click();await page.getByRole('dialog').getByRole('button',{name:'Sí, guardar pedido'}).click();
 await expect(page.getByRole('status')).toContainText('guardado');
 await page.getByLabel('Cuenta de prueba').selectOption('preview-warehouse');
 const details=page.getByRole('article').locator('[id^=order-details-]');
 await expect(details).toBeHidden();
 await expect(page.getByRole('button',{name:'Mostrar detalle',exact:true})).toHaveAttribute('aria-expanded','false');
 await page.getByRole('button',{name:'Mostrar detalle',exact:true}).click();
 await expect(details).toBeVisible();
 await expect(page.getByRole('article')).toContainText('Equipo de panadería');
 await expect(details.getByRole('group',{name:'Materia prima'})).toContainText('DEMO-001');
 await expect(details.getByRole('group',{name:'Insumos'})).toContainText('DEMO-007');
 await expect(details.getByRole('group',{name:'Insumos'})).toContainText('2 unidades');
 await page.getByRole('button',{name:'Ocultar detalle',exact:true}).click();
 await expect(details).toBeHidden();
 await page.getByRole('searchbox',{name:'Buscar pedidos'}).fill('DEMO-001');
 await expect(page.getByRole('article')).toHaveCount(1);
 const order=page.getByRole('article');
 await expect(order).not.toHaveClass(/registered-order/);
 await page.getByRole('checkbox',{name:'Registrado',exact:true}).check();
 await expect(order).toHaveClass(/registered-order/);
 await expect(order).toHaveCSS('border-left-color','rgb(40, 95, 73)');
 await expect(order).toHaveCSS('background-color','rgb(237, 246, 240)');
 await page.reload();
 await expect(order).toHaveClass(/registered-order/);
 await expect(page.getByRole('checkbox',{name:'Registrado',exact:true})).toBeChecked();
 await expect(page.getByRole('checkbox',{name:'Registrado',exact:true})).toBeDisabled();
 const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Descargar Excel'}).click();
 const download=await downloadPromise;expect(download.suggestedFilename()).toMatch(/\.xlsx$/);expect(await download.failure()).toBeNull();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
});
